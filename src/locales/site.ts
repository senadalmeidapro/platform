export function siteTranslations(language: 'en' | 'fr'): Record<string, string> {
  const result: Record<string, string> = Object.fromEntries(
    copy.map(([key, en, fr]) => [key, language === 'fr' ? fr : en]),
  );
  for (const entry of Object.values(serviceData))
    for (const [key, value] of Object.entries(entry)) {
      if (language === 'fr' && key.startsWith('fr.')) result[key.slice(3)] = value;
      if (language === 'en' && !key.startsWith('fr.')) result[key] = value;
    }
  return result;
}
